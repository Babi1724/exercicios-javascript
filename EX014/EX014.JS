//Verifique se dois números são iguais

let num1 = Number(prompt("Informe o primeiro numero: "));

let num2 = Number(prompt("Informe o segundo numero: "));


if( num1 == num2){

    alert(`O numero 1 ${num1} é igual ao numero 2 ${num2} `);
} 

else{
    alert(` O numero 2 ${num2} é igual ao numero 1 ${num1}`);
}
